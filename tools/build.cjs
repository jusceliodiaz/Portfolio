/**
 * Site build: SEO head on every page, German pages in /de/, sitemap.xml.
 *
 *   npm run build
 *
 * The English pages in the project root are the source of truth. This script:
 *  1. rewrites the SEO block of each English page (canonical, hreflang, Open Graph, Twitter, geo, JSON-LD);
 *  2. generates de/<page>.html from it, translating with i18n/de.json (missing strings stay English)
 *     and pointing asset paths one level up;
 *  3. writes sitemap.xml with en/de alternates.
 * Edit the English page (and add new strings to i18n/de.json), then run the build again.
 */
const fs = require('fs');
const path = require('path');
const { parseHTML } = require('linkedom');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://jdiaz.vercel.app';
const DE = JSON.parse(fs.readFileSync(path.join(ROOT, 'i18n/de.json'), 'utf8'));

// page → social image (assets/img/og/*.jpg, 1200×630, made by tools/og-images.cjs)
const PAGES = {
  index: 'og-home',
  projects: 'og-projects',
  automotive: 'og-automotive',
  archviz: 'og-archviz',
  'vr-realtime': 'og-vr-realtime',
  'ai-generative': 'og-ai-generative',
  cv: 'og-cv',
};
const urlOf = (page, lang) =>
  `${SITE}/${lang === 'de' ? 'de/' : ''}${page === 'index' ? '' : page + '.html'}`;

const PERSON = (lang) => ({
  '@context': 'https://schema.org',
  '@type': 'Person',
  name: 'Juscelio Diaz',
  url: urlOf('index', lang),
  image: `${SITE}/assets/img/og/og-home.jpg`,
  jobTitle:
    lang === 'de'
      ? '3D-Artist & Unreal Engine Technical Artist'
      : '3D Artist & Unreal Engine Technical Artist',
  address: { '@type': 'PostalAddress', addressLocality: 'Berlin', addressCountry: 'DE' },
  knowsLanguage: ['pt', 'en'],
  knowsAbout: [
    'Unreal Engine',
    'Architectural visualization',
    'Real-time 3D',
    'Virtual production',
    'Generative AI',
    'ComfyUI',
    '3ds Max',
  ],
  award: 'CGconnect 3D Awards 2026 — Winner, Interactive VR/AR Experience',
  sameAs: ['https://www.linkedin.com/in/typeforjd', 'https://www.instagram.com/jdworkviz/'],
});

const norm = (s) => s.replace(/\s+/g, ' ').trim();
const tr = (s) => DE[norm(s)] ?? null;

/* ---------- 1. SEO head ---------- */
function seoHead(document, page, lang) {
  const head = document.head;
  // drop everything this block owns, so the build is repeatable
  head
    .querySelectorAll(
      'link[rel=canonical], link[rel=alternate], meta[property^="og:"], meta[name^="twitter:"], meta[name^="geo."], meta[name="ICBM"], script[type="application/ld+json"]',
    )
    .forEach((el) => el.remove());
  [...head.childNodes]
    .filter((n) => n.nodeType === 8 && /seo:/.test(n.textContent))
    .forEach((n) => n.remove());

  const title = norm(document.title);
  const desc = norm(head.querySelector('meta[name=description]')?.getAttribute('content') || '');
  const img = `${SITE}/assets/img/og/${PAGES[page]}.jpg`;
  const url = urlOf(page, lang);
  const tags = [
    `<link rel="canonical" href="${url}" />`,
    `<link rel="alternate" hreflang="en" href="${urlOf(page, 'en')}" />`,
    `<link rel="alternate" hreflang="de" href="${urlOf(page, 'de')}" />`,
    `<link rel="alternate" hreflang="x-default" href="${urlOf(page, 'en')}" />`,
    `<meta property="og:type" content="${page === 'cv' ? 'profile' : 'website'}" />`,
    `<meta property="og:site_name" content="Juscelio Diaz" />`,
    `<meta property="og:locale" content="${lang === 'de' ? 'de_DE' : 'en_GB'}" />`,
    `<meta property="og:locale:alternate" content="${lang === 'de' ? 'en_GB' : 'de_DE'}" />`,
    `<meta property="og:url" content="${url}" />`,
    `<meta property="og:title" content="${title}" />`,
    `<meta property="og:description" content="${desc}" />`,
    `<meta property="og:image" content="${img}" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta property="og:image:alt" content="${title}" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${title}" />`,
    `<meta name="twitter:description" content="${desc}" />`,
    `<meta name="twitter:image" content="${img}" />`,
    `<meta name="geo.region" content="DE-BE" />`,
    `<meta name="geo.placename" content="Berlin" />`,
  ];
  if (page === 'index' || page === 'cv')
    tags.push(`<script type="application/ld+json">${JSON.stringify(PERSON(lang))}</script>`);
  const block = parseHTML(`<html><head>${tags.join('')}</head></html>`).document.head;
  const anchor = head.querySelector('link[rel=icon]') || head.lastChild;
  head.insertBefore(document.createComment(' seo: generated by tools/build.cjs '), anchor);
  [...block.childNodes].forEach((n) => head.insertBefore(n, anchor));
}

/* ---------- 2. translation ---------- */
const INLINE = new Set(['A', 'B', 'STRONG', 'EM', 'I', 'SPAN', 'BR', 'SUP', 'SMALL', 'ABBR', 'CODE']);
const SKIP = new Set(['SCRIPT', 'STYLE', 'SVG', 'PATH', 'NOSCRIPT']);
const hasText = (s) => /[A-Za-zÀ-ÿ]/.test(s);
const inlineOnly = (el) =>
  [...el.childNodes].every(
    (n) =>
      n.nodeType === 3 ||
      n.nodeType === 8 ||
      (n.nodeType === 1 && INLINE.has(n.tagName.toUpperCase()) && !n.querySelector('svg') && inlineOnly(n)),
  );

function translateTree(root, document) {
  root.normalize?.(); // the parser can split one sentence into several text nodes (e.g. around &amp;)
  for (const n of [...root.childNodes]) {
    if (n.nodeType === 3) {
      const t = hasText(n.textContent) && tr(n.textContent);
      // keep the surrounding whitespace; the text itself may span several source lines
      if (t) n.textContent = n.textContent.match(/^\s*/)[0] + t + n.textContent.match(/\s*$/)[0];
    } else if (n.nodeType === 1) {
      const tag = n.tagName.toUpperCase();
      if (SKIP.has(tag)) continue;
      if (tag === 'TEMPLATE') {
        const box = document.createElement('div');
        box.innerHTML = n.innerHTML;
        translateTree(box, document);
        translateAttrs(box);
        n.innerHTML = box.innerHTML;
        continue;
      }
      const directText = [...n.childNodes].some((c) => c.nodeType === 3 && hasText(c.textContent));
      const t =
        directText && n.children.length && !n.querySelector('svg') && inlineOnly(n) && tr(n.innerHTML);
      if (t) n.innerHTML = t;
      else translateTree(n, document);
    }
  }
}
function translateAttrs(root) {
  root.querySelectorAll('[alt], [aria-label], [title]').forEach((el) =>
    ['alt', 'aria-label', 'title'].forEach((a) => {
      const v = el.getAttribute(a);
      const t = v && tr(v);
      if (t) el.setAttribute(a, t);
    }),
  );
}

// assets live one level up from /de/; page links stay relative (de/ ↔ de/)
const up = (v) => (/^(assets\/|favicon\.svg)/.test(v) ? '../' + v : v);
function relocate(root) {
  root.querySelectorAll('style').forEach((st) => {
    st.textContent = st.textContent.replace(/url\((['"]?)assets\//g, 'url($1../assets/');
  });
  root.querySelectorAll('[src], [href], [poster], [data-poster-m], [data-image]').forEach((el) =>
    ['src', 'href', 'poster', 'data-poster-m', 'data-image'].forEach((a) => {
      if (el.hasAttribute(a)) el.setAttribute(a, up(el.getAttribute(a)));
    }),
  );
  root.querySelectorAll('[srcset]').forEach((el) =>
    el.setAttribute(
      'srcset',
      el
        .getAttribute('srcset')
        .split(',')
        .map((p) => up(p.trim()))
        .join(', '),
    ),
  );
}

// The language control (nav[data-lang-switch]) always shows both languages: EN | DE.
// The current one is marked aria-current; each link points at the same page in that language.
const GLOBE =
  '<svg class="lang-globe" viewBox="0 0 256 256" width="14" height="14" fill="currentColor" aria-hidden="true"><path d="M128,20A108,108,0,1,0,236,128,108.12,108.12,0,0,0,128,20Zm83.13,96H179.56a144.3,144.3,0,0,0-21.35-66.36A84.22,84.22,0,0,1,211.13,116ZM128,207c-9.36-10.81-24.46-33.13-27.45-67h54.94a119.74,119.74,0,0,1-17.11,52.77A108.61,108.61,0,0,1,128,207Zm-27.45-91a119.74,119.74,0,0,1,17.11-52.77A108.61,108.61,0,0,1,128,49c9.36,10.81,24.46,33.13,27.45,67ZM97.79,49.64A144.3,144.3,0,0,0,76.44,116H44.87A84.22,84.22,0,0,1,97.79,49.64ZM44.87,140H76.44a144.3,144.3,0,0,0,21.35,66.36A84.22,84.22,0,0,1,44.87,140Zm113.34,66.36A144.3,144.3,0,0,0,179.56,140h31.57A84.22,84.22,0,0,1,158.21,206.36Z"/></svg>';
function langSwitch(document, page, lang) {
  const href = (target) =>
    target === lang ? `${page}.html` : target === 'de' ? `de/${page}.html` : `../${page}.html`;
  const link = (target, name) =>
    `<a href="${href(target)}" hreflang="${target}" lang="${target}" title="${name}"` +
    (target === lang ? ' aria-current="true"' : '') +
    `><span class="visually-hidden">${name}</span><span aria-hidden="true">${target.toUpperCase()}</span></a>`;
  document.querySelectorAll('nav[data-lang-switch]').forEach((nav) => {
    nav.setAttribute('aria-label', lang === 'de' ? 'Sprache' : 'Language');
    nav.innerHTML = GLOBE + link('en', 'English') + link('de', 'Deutsch');
  });
}

/* ---------- run ---------- */
fs.mkdirSync(path.join(ROOT, 'de'), { recursive: true });
let missing = new Set();
for (const page of Object.keys(PAGES)) {
  const file = path.join(ROOT, page + '.html');
  const src = fs.readFileSync(file, 'utf8');

  // English page: SEO block + switch
  const en = parseHTML(src).document;
  en.documentElement.setAttribute('lang', 'en');
  seoHead(en, page, 'en');
  langSwitch(en, page, 'en');
  fs.writeFileSync(file, '<!doctype html>\n' + en.documentElement.outerHTML + '\n');

  // German page
  const de = parseHTML(src).document;
  de.documentElement.setAttribute('lang', 'de');
  const title = tr(de.title);
  if (title) de.title = title;
  const meta = de.querySelector('meta[name=description]');
  if (meta && tr(meta.getAttribute('content')))
    meta.setAttribute('content', tr(meta.getAttribute('content')));
  translateTree(de.body, de);
  translateAttrs(de);
  relocate(de);
  // lightbox content lives in <template> (not reached by querySelectorAll): relocate it on a copy
  de.querySelectorAll('template').forEach((t) => {
    const box = de.createElement('div');
    box.innerHTML = t.innerHTML;
    relocate(box);
    t.innerHTML = box.innerHTML;
  });
  seoHead(de, page, 'de');
  langSwitch(de, page, 'de');
  fs.writeFileSync(
    path.join(ROOT, 'de', page + '.html'),
    '<!doctype html>\n' + de.documentElement.outerHTML + '\n',
  );
}

/* ---------- 3. sitemap ---------- */
const today = new Date().toISOString().slice(0, 10);
const entry = (page, lang) => `  <url>
    <loc>${urlOf(page, lang)}</loc>
    <lastmod>${today}</lastmod>
    <xhtml:link rel="alternate" hreflang="en" href="${urlOf(page, 'en')}" />
    <xhtml:link rel="alternate" hreflang="de" href="${urlOf(page, 'de')}" />
    <xhtml:link rel="alternate" hreflang="x-default" href="${urlOf(page, 'en')}" />
  </url>`;
fs.writeFileSync(
  path.join(ROOT, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${Object.keys(PAGES)
  .flatMap((p) => [entry(p, 'en'), entry(p, 'de')])
  .join('\n')}
</urlset>
`,
);
console.log('built', Object.keys(PAGES).length, 'pages × 2 languages + sitemap.xml');
